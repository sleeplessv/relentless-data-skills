def project_root() -> Path:
    here = Path.cwd().resolve()
    home = Path.home().resolve()
    for base in [here, *here.parents]:
        if (base / ".git").exists():
            return base
        if base == home:
            break
    return here


ROOT = project_root()
CTX_DIR = ROOT / ".metabase"
CTX_FILE = CTX_DIR / "context.md"
BACKUP_DIR = CTX_DIR / "restore-points"


def parse_env_line(line: str):
    line = line.strip()
    if line.startswith("export "):
        line = line[7:].lstrip()
    if not line or line.startswith("#") or "=" not in line:
        return None
    k, v = line.split("=", 1)
    k, v = k.strip(), v.strip()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", k):
        return None
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        v = v[1:-1]                       # matched quote pair only
    else:
        v = re.sub(r"\s+#.*$", "", v).strip()   # unquoted trailing comment
    return k, v


def load_env_files() -> dict:
    found, seen = {}, set()
    here = Path.cwd().resolve()
    bases = [here, *here.parents]
    if ROOT not in bases:
        bases.append(ROOT)
    for base in bases:
        for rel in ENV_CANDIDATES:
            p = (base / rel).resolve()
            if p in seen or not p.is_file():
                continue
            seen.add(p)
            for line in p.read_text(errors="ignore").splitlines():
                kv = parse_env_line(line)
                if kv:
                    found.setdefault(kv[0], (kv[1], str(p)))
        if (base / ".git").exists():
            break
    return found


def context_url():
    if not CTX_FILE.is_file():
        return None
    m = re.search(r"^url:\s*(\S+)", CTX_FILE.read_text(), re.M)
    return m.group(1).strip("'\"") if m else None


_CFG = {}


def config() -> tuple[str, str]:
    if _CFG:
        return _CFG["url"], _CFG["key"]
    env = load_env_files()
    key = os.environ.get("METABASE_API_KEY")
    key_src = "process environment"
    if not key and "METABASE_API_KEY" in env:
        key, key_src = env["METABASE_API_KEY"]
        key_src = f"{key_src}"
    url = os.environ.get("METABASE_URL")
    url_src = "process environment"
    if not url:
        url = context_url()
        url_src = str(CTX_FILE)
    if not url and "METABASE_URL" in env:
        url, url_src = env["METABASE_URL"]

    missing = []
    if not key:
        missing.append("METABASE_API_KEY (process env or a .env file)")
    if not url:
        missing.append(f"METABASE_URL (process env, {CTX_FILE} frontmatter, "
                       f"or a .env file)")
    if missing:
        die("missing config: " + "; ".join(missing) +
            f"\n  project root: {ROOT}"
            f"\n  run `mb bootstrap` once METABASE_URL is set")
    if not url.startswith(("http://", "https://")):
        die(f"METABASE_URL must start with http:// or https:// (got {url!r} "
            f"from {url_src})")
    _CFG.update(url=url.rstrip("/"), key=key,
                url_src=url_src, key_src=key_src)
    return _CFG["url"], _CFG["key"]


# ---------------------------------------------------------------- transport

def api(method: str, path: str, body=None, form=None, raw=False, timeout=120,
        allow_fail=False):
    """Call the Metabase API.

    `path` is relative to /api — pass "/card/5", NOT "/api/card/5" (that
    yields /api/api/card/5 and a 404 that reads like a missing endpoint).
    allow_fail=True returns None on an HTTP error instead of exiting, for
    probes where "not found" is a legitimate answer.
    """
    url, key = config()
    headers = {"x-api-key": key}
    data = None
    if form is not None:
        data = urllib.parse.urlencode(form).encode()
        headers["Content-Type"] = "application/x-www-form-urlencoded"
    elif body is not None:
        data = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    try:
        req = urllib.request.Request(f"{url}/api{path}", data=data,
                                     method=method, headers=headers)
        with urllib.request.urlopen(req, timeout=timeout) as r:
            payload = r.read()
    except urllib.error.HTTPError as e:
        if allow_fail:
            return None
        detail = e.read().decode(errors="replace")[:800]
        extra = ""
        if e.code in (401, 403):
            extra = f"\n  key from: {_CFG.get('key_src', '?')}"
        print(f"HTTP {e.code} on {method} {url}/api{path}{extra}\n{detail}",
              file=sys.stderr)
        sys.exit(1)
    except urllib.error.URLError as e:
        print(f"connection failed to {url} (from {_CFG.get('url_src','?')}): "
              f"{e.reason}\n"
              f"  If the host resolved but timed out: check the VPN, and that "
              f"the shell is unsandboxed.\n"
              f"  If the host did not resolve: check METABASE_URL for a typo.",
              file=sys.stderr)
        sys.exit(1)
    except ValueError as e:
        print(f"bad URL {url!r} (from {_CFG.get('url_src','?')}): {e}",
              file=sys.stderr)
        sys.exit(1)
    if raw:
        return payload.decode(errors="replace")
    return json.loads(payload) if payload else None


def out(obj):
    print(json.dumps(obj, indent=2, default=str))


