# ---------------------------------------------------------------- read-only

LEADING_OK = {"SELECT", "WITH", "SHOW", "EXPLAIN", "TABLE", "VALUES",
              "DESCRIBE", "DESC"}

# Dangerous *inside* an otherwise read-only statement — chiefly via
# data-modifying CTEs (WITH x AS (DELETE ...)) and FOR UPDATE row locks.
# Keywords that are only dangerous as a statement's first token (SET, COPY,
# CALL, COMMENT, CLUSTER, LOCK, EXECUTE, IMPORT, RESET, SECURITY, VACUUM,
# REINDEX, REFRESH, PREPARE, DISCARD) are deliberately absent: LEADING_OK plus
# the single-statement rule already make them unreachable, and blocking them
# anywhere false-positives on ordinary column names like `comment` or `set`.
ALWAYS_BLOCKED = {
    "INSERT", "UPDATE", "DELETE", "MERGE", "TRUNCATE", "DROP", "CREATE",
    "ALTER", "GRANT", "REVOKE",
}

# Read-only-looking functions that write, kill sessions, or read the filesystem.
# The keyword scan cannot see these: their payload lives in a string literal,
# which strip_sql (correctly) blanks.
FUNC_DENY = {
    "dblink", "dblink_exec", "dblink_send_query",
    "nextval", "setval",
    "lo_import", "lo_export", "lo_unlink",
    "pg_read_file", "pg_read_binary_file", "pg_ls_dir", "pg_stat_file",
    "pg_terminate_backend", "pg_cancel_backend",
    "pg_reload_conf", "pg_rotate_logfile", "pg_switch_wal",
    "pg_create_restore_point", "pg_drop_replication_slot",
    "pg_logical_slot_get_changes", "query_to_xml", "pg_sleep",
}


class Unterminated(Exception):
    pass


def strip_sql(sql: str) -> str:
    """Blank comments and string literals so nothing hides inside them.

    Handles dollar-quoting ($$..$$, $tag$..$tag$) and E'' backslash escapes.
    Raises Unterminated if a literal or block comment never closes — failing
    loudly beats silently swallowing the rest of the statement, which is how a
    hidden second statement slips through.
    """
    out = []
    i, n = 0, len(sql)
    while i < n:
        # dollar-quoted string: $$...$$ or $tag$...$tag$
        m = re.match(r"\$([A-Za-z_][A-Za-z_0-9]*)?\$", sql[i:])
        if m:
            tag = m.group(0)
            end = sql.find(tag, i + len(tag))
            if end == -1:
                raise Unterminated(f"unterminated dollar-quoted string {tag}")
            out.append(" ")
            i = end + len(tag)
            continue
        two = sql[i:i + 2]
        if two == "/*":
            depth, i = 1, i + 2
            while i < n and depth:
                if sql[i:i + 2] == "/*":
                    depth += 1
                    i += 2
                elif sql[i:i + 2] == "*/":
                    depth -= 1
                    i += 2
                else:
                    i += 1
            if depth:
                raise Unterminated("unterminated block comment")
            out.append(" ")
        elif two == "--":
            while i < n and sql[i] != "\n":
                i += 1
            out.append(" ")
        elif sql[i] in "'\"":
            q = sql[i]
            # E'...' / e'...' honours backslash escapes
            esc = q == "'" and i > 0 and sql[i - 1] in "Ee" and (
                i < 2 or not (sql[i - 2].isalnum() or sql[i - 2] == "_"))
            i += 1
            closed = False
            while i < n:
                c = sql[i]
                if esc and c == "\\" and i + 1 < n:
                    i += 2
                    continue
                if c == q:
                    if i + 1 < n and sql[i + 1] == q:  # '' escape
                        i += 2
                        continue
                    i += 1
                    closed = True
                    break
                i += 1
            if not closed:
                raise Unterminated("unterminated string literal")
            out.append(" ")
        else:
            out.append(sql[i])
            i += 1
    return "".join(out)


def assert_readonly(sql: str) -> None:
    try:
        clean = strip_sql(sql).strip()
    except Unterminated as e:
        die(str(e))
    if not clean:
        die("empty query")

    body = clean.rstrip()
    if body.endswith(";"):
        body = body[:-1]
    if ";" in body:
        die("multiple statements — submit one statement at a time")

    lead = body.lstrip("﻿ \t\r\n(")
    first = re.match(r"[A-Za-z]+", lead)
    if not first or first.group(0).upper() not in LEADING_OK:
        got = first.group(0).upper() if first else "?"
        die(f"leading keyword {got!r} is not read-only "
            f"(allowed: {', '.join(sorted(LEADING_OK))})")

    words = [w.upper() for w in re.findall(r"[A-Za-z_][A-Za-z_0-9]*", body)]
    hits = sorted(set(words) & ALWAYS_BLOCKED)
    if hits:
        die(f"write/DDL keyword(s) present: {', '.join(hits)}")

    # SELECT ... INTO newtable is DDL wearing a SELECT hat.
    for idx, w in enumerate(words):
        if w == "INTO" and (idx == 0 or words[idx - 1] != "INSERT"):
            die("SELECT … INTO creates a table — use a plain SELECT")

    fns = sorted({w.lower() for w in words} & FUNC_DENY)
    if fns:
        die(f"function(s) with side effects: {', '.join(fns)}")


def die(reason: str) -> None:
    print(f"BLOCKED: {reason}", file=sys.stderr)
    sys.exit(2)


