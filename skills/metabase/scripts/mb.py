#!/usr/bin/env python3
"""mb — Metabase API wrapper.

Reads run freely. Ad-hoc SQL is checked read-only. Every mutation captures a
restore point first.

Resolution:
  METABASE_URL  process env -> .metabase/context.md frontmatter -> .env files
  METABASE_API_KEY  process env -> .env files   (context.md never holds the key)

Both the context file and .env discovery are anchored at the project root (the
nearest ancestor containing .git), so the tool behaves identically from any
subdirectory.

The read-only check is a speed bump, not a sandbox. A determined writer can get
past any string-level check (see FUNC_DENY). The durable control is a read-only
database role on the Metabase connection.
"""

